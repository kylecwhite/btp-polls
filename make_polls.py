"""Generate polls.js for the whole course from each session's poll manifest.

    python3 make_polls.py 7=../07_Housekeeping_I/polling/HK1_polls.json [8=...] [--only 7:1,7]

Poll ids are s<session>-p<n>, e.g. s07-p01, so one link serves every session.
A re-vote (same patient, same options, later in the same session) is paired
with the first vote automatically, so the board can show them side by side.
"""
import json, sys

args = [a for a in sys.argv[1:] if not a.startswith('--')]
only = {}
if '--only' in sys.argv:
    for part in sys.argv[sys.argv.index('--only') + 1].split(';'):
        s, ns = part.split(':')
        only[int(s)] = {int(x) for x in ns.split(',')}

polls = []
for arg in args:
    if '=' not in arg:
        continue
    sess, path = arg.split('=', 1)
    sess = int(sess)
    d = json.load(open(path))
    mine = []
    for p in d['polls']:
        if sess in only and p['n'] not in only[sess]:
            continue
        pat = p.get('patient') or ''
        name, _, when = [s.strip() for s in pat.partition('·')] if pat else ('', '', '')
        mine.append({
            'id': f"s{sess:02d}-p{p['n']:02d}",
            'session': sess,
            'n': p['n'],
            'slide': p['slide'],
            'label': p.get('label') or 'POLLING QUESTION',
            'patient': ({'name': name.title(), 'when': when.title(), 'lines': p.get('patientLines') or [],
                         'tag': p.get('patientTag')} if pat else None),
            'context': p.get('context'),
            'question': p['question'],
            'options': p['options'],
            'multi': (p.get('allowedSelections') or 1) > 1,
            'deck': d.get('deck'),
        })
    for i, q in enumerate(mine):
        for e in mine[:i]:
            if q['patient'] and e['patient'] and q['patient']['name'] == e['patient']['name'] and q['options'] == e['options']:
                q['compareWith'] = e['id']
    polls += mine

js = ("// Generated by make_polls.py from each session's poll manifest. Do not edit by hand.\n"
      "export const POLLS = " + json.dumps(polls, indent=2, ensure_ascii=False) + ";\n")
open('polls.js', 'w').write(js)
for p in polls:
    print(p['id'], 'slide', p['slide'], (p['patient'] or {}).get('name', ''), '| compare', p.get('compareWith', '-'))
