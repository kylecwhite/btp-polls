"""Generate polls.js from a session manifest (HK1_polls.json).
   python3 make_polls.py MANIFEST [--only 1,7]"""
import json, sys, re
src = sys.argv[1]
only = None
if '--only' in sys.argv:
    only = {int(x) for x in sys.argv[sys.argv.index('--only') + 1].split(',')}
d = json.load(open(src))
polls = []
for p in d['polls']:
    if only and p['n'] not in only:
        continue
    pat = p.get('patient') or ''
    name, _, when = [s.strip() for s in pat.partition('·')] if pat else ('', '', '')
    polls.append({
        'id': f"p{p['n']:02d}",
        'n': p['n'],
        'slide': p['slide'],
        'label': p.get('label') or 'POLLING QUESTION',
        'patient': ({'name': name.title(), 'when': when.title(), 'lines': p.get('patientLines') or [],
                     'tag': p.get('patientTag')} if pat else None),
        'context': p.get('context'),
        'question': p['question'],
        'options': p['options'],
        'multi': (p.get('allowedSelections') or 1) > 1,
    })
# A re-vote: same patient name and identical options as an earlier poll -> compare with it
for i, q in enumerate(polls):
    for e in polls[:i]:
        if q['patient'] and e['patient'] and q['patient']['name'] == e['patient']['name'] and q['options'] == e['options']:
            q['compareWith'] = e['id']
out = {'hk1': {'title': 'Housekeeping I', 'session': 7, 'deck': d.get('deck'), 'polls': polls}}
js = ("// Generated by make_polls.py from HK1_polls.json. Do not edit by hand.\n"
      "export const SESSIONS = " + json.dumps(out, indent=2, ensure_ascii=False) + ";\n")
open('polls.js', 'w').write(js)
print(len(polls), 'polls:', [(p['id'], p['slide'], p.get('compareWith')) for p in polls])
